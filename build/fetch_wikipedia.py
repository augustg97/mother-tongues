#!/usr/bin/env python3
"""fetch_wikipedia.py — does this language have an encyclopedia written in it, and is anyone
writing it? Register D12.

WHY THIS IS A FACT WORTH HAVING. Everything else in this museum looks backwards: manuscripts,
inscriptions, first attestations, a UDHR translation made once in the 1990s. None of it says
whether a language is being *written today, by its own speakers, about anything they choose*.
A Wikipedia does. It is the largest body of contemporary prose that exists for most of the
world's smaller written languages, and its size and edit rate are published numbers.

It also carries one of the sharpest facts in the whole atlas. Cebuano's Wikipedia is among the
largest in the world by article count and almost all of it was generated by one bot; Swedish is
in the same position. Meanwhile Hausa, with tens of millions of speakers, has a fraction of
that. So article count alone is misleading, and the honest measure is carried alongside it:
ACTIVE EDITORS — how many people made five or more edits last month. That number cannot be
inflated by a script, and it is the one that says whether a language is being written.

Everything here comes from the Wikimedia API:
  sitematrix          every language edition, with its language code and local name
  siteinfo/statistics articles, edits, active users
Licensed CC-BY-SA, which SCOPE §12 D3 permits.

The join is the same one the alphabets use: Wikipedia's code is a language code, which reaches
ISO 639-3 through the mapping already cached by fetch_alphabets.py, and thence a glottocode.
Codes Wikipedia uses that are not ISO 639-1 (`ceb`, `war`, `nah`, `zh-yue`) are handled as
three-letter codes or by the same bridge, and anything that will not resolve is reported rather
than dropped silently.

Run: python3 fetch_wikipedia.py
"""
from __future__ import annotations

import json
import os
import ssl
import time
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "data", "wikipedia")
WEB = os.path.join(HERE, "..", "web", "data")
ALPH = os.path.join(HERE, "..", "data", "alphabets", "cldr_characters.json")
UA = "MotherTongues/1.0 (research atlas of human languages; augustgweon@gmail.com)"

# Wikipedia codes that are not the language's ISO 639-3, mapped to the Glottolog NAME so the
# resolution is by name and checked by machine, exactly as the alphabet bridge is.
WP_BRIDGE = {
    "zh": "Mandarin Chinese", "yue": "Yue Chinese", "wuu": "Wu Chinese",
    "nan": "Min Nan Chinese", "hak": "Hakka Chinese", "gan": "Gan Chinese",
    "cdo": "Min Dong Chinese", "zh-yue": "Yue Chinese", "zh-min-nan": "Min Nan Chinese",
    "ar": "Standard Arabic", "arz": "Egyptian Arabic", "ary": "Moroccan Arabic",
    "ary-x": "Moroccan Arabic", "fa": "Western Farsi", "ms": "Standard Malay",
    "uz": "Northern Uzbek", "az": "North Azerbaijani", "ku": "Northern Kurdish",
    "mn": "Halh Mongolian", "sw": "Swahili", "om": "West Central Oromo",
    "ne": "Nepali", "ps": "Northern Pashto", "et": "Estonian", "sq": "Northern Tosk Albanian",
    "sr": "Serbian-Croatian-Bosnian", "hr": "Serbian-Croatian-Bosnian",
    "bs": "Serbian-Croatian-Bosnian", "sh": "Serbian-Croatian-Bosnian",
    "no": "Norwegian", "nb": "Norwegian", "nn": "Norwegian", "yi": "Eastern Yiddish",
    "mg": "Plateau Malagasy", "gn": "Paraguayan Guaraní", "iu": "Eastern Canadian Inuktitut",
    "kok": "Goan Konkani", "qu": "Cusco Quechua", "za": "Yongbei Zhuang",
    "bxr": "Russia Buriat", "als": "Central Alemannic", "nds": "Eastern Low German",
    "bat-smg": "Lithuanian", "be-tarask": "Belarusian",
    "cbk-zam": "Chavacano", "fiu-vro": "South Estonian",
    # roa-tara (Tarantino) and map-bms (Banyumasan) have no language-level Glottolog node, so
    # they are left to fall through and be reported rather than attached to a near neighbour.
}

# Editions that are not a natural language and are excluded on that ground.
WP_SKIP = {"eo", "io", "ia", "ie", "jbo", "vo", "nov", "avk", "tok", "simple", "test",
           "meta", "commons", "species", "wikidata", "mul", "zh-classical", "lzh",
           "got", "cu", "la", "ang", "non", "sga", "pi", "sa"}


def get(url: str, tries: int = 3):
    ctx = ssl.create_default_context()
    last = None
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA})
            with urllib.request.urlopen(req, timeout=60, context=ctx) as r:
                return json.load(r)
        except Exception as e:                               # noqa: BLE001
            last = e
            time.sleep(2 * (i + 1))
    print(f"   failed {url[:70]}: {last}")
    return None


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    print("1. every Wikipedia language edition (sitematrix)")
    sm = get("https://meta.wikimedia.org/w/api.php?action=sitematrix&format=json"
             "&smtype=language&smstate=all")
    if not sm:
        raise SystemExit("could not read sitematrix")
    eds = []
    for k, v in (sm.get("sitematrix") or {}).items():
        if not k.isdigit():
            continue
        code = v.get("code")
        if not code or code in WP_SKIP:
            continue
        wiki = next((s for s in (v.get("site") or [])
                     if s.get("code") == "wiki" and not s.get("closed")), None)
        if not wiki:
            continue
        eds.append({"code": code, "name": v.get("name", ""),
                    "localname": v.get("localname", ""), "url": wiki["url"]})
    print(f"   {len(eds)} open Wikipedia editions in a natural language")

    print("2. statistics per edition")
    stats: dict[str, dict] = {}
    for i, e in enumerate(eds):
        j = get(e["url"] + "/w/api.php?action=query&format=json&formatversion=2"
                           "&meta=siteinfo&siprop=statistics")
        if not j:
            continue
        st = (j.get("query") or {}).get("statistics") or {}
        stats[e["code"]] = {"articles": int(st.get("articles") or 0),
                            "edits": int(st.get("edits") or 0),
                            "users": int(st.get("users") or 0),
                            "active": int(st.get("activeusers") or 0),
                            "name": e["name"], "localname": e["localname"],
                            "url": e["url"]}
        if (i + 1) % 60 == 0:
            print(f"   {i+1}/{len(eds)}")
        time.sleep(0.12)
    print(f"   {len(stats)} editions reported statistics")

    json.dump({"by_code": stats,
               "source": "Wikimedia sitematrix and siteinfo/statistics",
               "licence": "CC-BY-SA-4.0",
               "retrieved": time.strftime("%Y-%m-%d")},
              open(os.path.join(OUT, "editions.json"), "w"), ensure_ascii=False)
    tot = sum(v["articles"] for v in stats.values())
    print(f"\nwrote data/wikipedia/editions.json — {tot:,} articles across "
          f"{len(stats)} languages")
    big = sorted(stats.items(), key=lambda kv: -kv[1]["articles"])[:8]
    for c, v in big:
        per = v["articles"] / max(v["active"], 1)
        print(f"   {c:12s} {v['articles']:>9,} articles  {v['active']:>6,} active editors "
              f"  {per:>9,.0f} articles per active editor")
